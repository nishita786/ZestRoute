-- ZestRoute Snowflake setup
-- Creates warehouse, database, schema, and stage objects for delivery analytics.

USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS ZESTROUTE_WH
  WITH WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS ZESTROUTE_DB;
CREATE SCHEMA IF NOT EXISTS ZESTROUTE_DB.DELIVERY_ANALYTICS;

USE WAREHOUSE ZESTROUTE_WH;
USE DATABASE ZESTROUTE_DB;
USE SCHEMA DELIVERY_ANALYTICS;

-- Replace <YOUR_S3_BUCKET> with the project data-lake bucket name.
CREATE OR REPLACE STAGE zestroute_s3_stage
  URL = 's3://<YOUR_S3_BUCKET>/processed/'
  FILE_FORMAT = (TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"');

CREATE OR REPLACE FILE FORMAT zestroute_csv_format
  TYPE = CSV
  SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  NULL_IF = ('', 'NULL', 'null', 'NaN');
