-- Load processed delivery orders into Snowflake from the S3 stage.
-- Alternative: load clean_orders.csv with Snowsight UI into ORDERS.

USE WAREHOUSE ZESTROUTE_WH;
USE DATABASE ZESTROUTE_DB;
USE SCHEMA DELIVERY_ANALYTICS;

CREATE OR REPLACE TABLE ORDERS (
  ID STRING,
  DELIVERY_PERSON_ID STRING,
  DELIVERY_PERSON_AGE FLOAT,
  DELIVERY_PERSON_RATINGS FLOAT,
  RESTAURANT_LATITUDE FLOAT,
  RESTAURANT_LONGITUDE FLOAT,
  DELIVERY_LOCATION_LATITUDE FLOAT,
  DELIVERY_LOCATION_LONGITUDE FLOAT,
  ORDER_DATE DATE,
  ORDER_MONTH STRING,
  ORDER_DAY STRING,
  TIME_ORDERD STRING,
  TIME_ORDER_PICKED STRING,
  PICKUP_LAG_MIN FLOAT,
  WEATHERCONDITIONS STRING,
  ROAD_TRAFFIC_DENSITY STRING,
  VEHICLE_CONDITION NUMBER,
  TYPE_OF_ORDER STRING,
  TYPE_OF_VEHICLE STRING,
  MULTIPLE_DELIVERIES FLOAT,
  FESTIVAL STRING,
  CITY STRING,
  TIME_TAKEN_MIN FLOAT,
  DELIVERY_PERFORMANCE STRING,
  IS_WEEKEND STRING
);

